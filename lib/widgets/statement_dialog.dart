  String _formatDate(DateTime dt) {
    final y = dt.year.toString().padLeft(4, '0');
    final m = dt.month.toString().padLeft(2, '0');
    final d = dt.day.toString().padLeft(2, '0');
    final h = dt.hour.toString().padLeft(2, '0');
    final min = dt.minute.toString().padLeft(2, '0');
    return '$y-$m-$d $h:$min';
  }

  String _formatDateOnly(DateTime dt) {
    final y = dt.year.toString().padLeft(4, '0');
    final m = dt.month.toString().padLeft(2, '0');
    final d = dt.day.toString().padLeft(2, '0');
    return '$y-$m-$d';
  }

  String _generateStatementRef() {
    final cleanId = widget.friend.id.replaceAll(RegExp(r'[^0-9]'), '');
    final suffix = cleanId.length >= 6
        ? cleanId.substring(cleanId.length - 6)
        : widget.friend.id.hashCode.abs().toString().padLeft(6, '0').substring(0, 6);
    final now = DateTime.now();
    final ymd =
        '${now.year}${now.month.toString().padLeft(2, '0')}${now.day.toString().padLeft(2, '0')}';
    return 'STM-$ymd-$suffix';
  }

  String _buildTextStatement() {
    final buffer = StringBuffer();
    final ref = _generateStatementRef();
    final now = DateTime.now();

    buffer.writeln('==================================================');
    buffer.writeln('          LEDGER STATEMENT OF ACCOUNT');
    buffer.writeln('==================================================');
    buffer.writeln('Reference:      $ref');
    buffer.writeln('Issue Date:     ${_formatDate(now)}');
    buffer.writeln('Account Holder: ${widget.friend.name.toUpperCase()}');
    buffer.writeln('Currency:       MAD (Moroccan Dirham)');

    final statusStr = widget.friend.amountOwed > 0
        ? 'THEY OWE YOU (+${widget.friend.amountOwed.toStringAsFixed(2)} MAD)'
        : widget.friend.amountOwed < 0
            ? 'YOU OWE THEM (-${widget.friend.amountOwed.abs().toStringAsFixed(2)} MAD)'
            : 'SETTLED (0.00 MAD)';
    buffer.writeln('Status:         $statusStr');
    buffer.writeln('--------------------------------------------------');
    buffer.writeln('TRANSACTION HISTORY:');
    buffer.writeln('#   DATE       TYPE   AMOUNT (MAD)  BALANCE  REASON');
    buffer.writeln('--------------------------------------------------');

    double running = 0.0;
    for (int i = 0; i < widget.friend.transactions.length; i++) {
      final tx = widget.friend.transactions[i];
      running += tx.amount;
      final typeStr = tx.amount >= 0 ? 'LENT ' : 'BORR ';
      final amtStr =
          (tx.amount >= 0 ? '+' : '') + tx.amount.toStringAsFixed(2);
      final balStr =
          (running >= 0 ? '+' : '') + running.toStringAsFixed(2);
      final dateStr = _formatDateOnly(tx.date);
      final editTag = tx.isEdited ? ' [Amended]' : '';
      buffer.writeln(
          '${(i + 1).toString().padRight(3)} $dateStr  $typeStr ${amtStr.padLeft(11)}  ${balStr.padLeft(8)}  ${tx.reason}$editTag');
    }

    buffer.writeln('--------------------------------------------------');
    buffer.writeln(
        'NET OUTSTANDING BALANCE: ${(widget.friend.amountOwed >= 0 ? '+' : '')}${widget.friend.amountOwed.toStringAsFixed(2)} MAD');

    if (widget.friend.borrowedItems.isNotEmpty) {
      buffer.writeln('--------------------------------------------------');
      buffer.writeln('TRACKED OBJECTS / ITEMS:');
      for (var item in widget.friend.borrowedItems) {
        final dir = item.isLentByMe ? 'Lent out' : 'Borrowed';
        final status = item.isReturned
            ? 'Returned (${_formatDateOnly(item.returnedDate ?? item.date)})'
            : 'Active';
        buffer.writeln('- ${item.name} ($dir) | $status | Notes: ${item.notes.isEmpty ? 'None' : item.notes}');
      }
    }

    buffer.writeln('==================================================');
    buffer.writeln('Generated by Ledger App • Simple, Fast & Offline');
    buffer.writeln('==================================================');
    return buffer.toString();
  }

  Future<void> _shareImage() async {
    setState(() => _isExporting = true);
    try {
      // Allow widget tree to settle
      await Future.delayed(const Duration(milliseconds: 100));

      final boundary = _statementKey.currentContext?.findRenderObject()
          as RenderRepaintBoundary?;

      if (boundary == null) {
        throw Exception("Could not find statement render view.");
      }

      final ui.Image image = await boundary.toImage(pixelRatio: 3.0);
      final byteData =
          await image.toByteData(format: ui.ImageByteFormat.png);

      if (byteData == null) {
        throw Exception("Failed to generate statement image bytes.");
      }

      final pngBytes = byteData.buffer.asUint8List();

      final tempDir = await getTemporaryDirectory();
      final sanitizedName =
          widget.friend.name.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final stamp = DateTime.now().millisecondsSinceEpoch;
      final filePath =
          '${tempDir.path}/statement_${sanitizedName}_$stamp.png';
      final file = File(filePath);
      await file.writeAsBytes(pngBytes, flush: true);

      if (!mounted) return;

      final ref = _generateStatementRef();
      await SharePlus.instance.share(
        ShareParams(
          files: [XFile(file.path, mimeType: 'image/png')],
          text:
              'Statement of Account ($ref) for ${widget.friend.name} - Ledger App',
        ),
      );
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text("Error sharing statement image: $e"),
          backgroundColor: const Color(0xFFD71921),
        ),
      );
    } finally {
      if (mounted) setState(() => _isExporting = false);
    }
  }

